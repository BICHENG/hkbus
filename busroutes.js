  /* 当前时段的班距（分钟）；没有对应时段返回 null */
  function freqNow(route, dir, d = new Date()){
    const r = routes[route + '|' + dir];
    if (!r || !r.freq) return null;
    const hhmm = [String(d.getHours()).padStart(2,'0'), String(d.getMinutes()).padStart(2,'0')].join(':');
    const bands = r.freq[dayType(d)] || [];
    for (const [a, b, m] of bands) if (hhmm >= a && hhmm < b) return m;
    return null;
  }
  /* 尾班车还有多久开（分钟） */
  function lastBusIn(route, dir, d = new Date()){
    const r = routes[route + '|' + dir];
    if (!r) return null;
    const [h, m] = r.last.split(':').map(Number);
    let t = new Date(d); t.setHours(h, m, 0, 0);
    if (t <= d) t = new Date(t.getTime() + 86400000);
    return Math.round((t - d) / 60000);
  }

